def build_precompiled_image(runtime_dir: Path, force: bool = False) -> Path:
    """Build precompiled SBCL Maxima image stackmaxima.core and maxima-optimised."""
    stack_dir = runtime_dir / "stack"
    core_path = stack_dir / "stackmaxima.core"
    wrapper_path = stack_dir / "maxima-optimised"
    qtype_dir = runtime_dir / "qtype_stack"
    maxima_code_path = qtype_dir / "stack" / "maxima"

    if core_path.exists() and wrapper_path.exists() and not force:
        return wrapper_path

    build_script = f"""
:lisp (remprop (quote mbox) (quote operators))
:lisp (setq *inconsistent-declarations* (remove-if (lambda (p) (member (car p) (quote ($lassociative $rassociative)))) *inconsistent-declarations*))
file_search_maxima:append([sconcat("{maxima_code_path}/###.{{mac,mc}}")], file_search_maxima)$
file_search_lisp:append([sconcat("{maxima_code_path}/###.{{lisp}}")], file_search_lisp)$
load("stackmaxima.mac")$
%_ce_rem(ex) := block([ex2, simp:false],
  if safe_op(ex) = "" then return(ex),
  if safe_op(ex) = "(" and safe_op(first(args(ex))) = "%_C" then return(%_ce_rem(second(args(ex)))),
  if safe_op(ex) = "(" and safe_op(first(args(ex))) = "%_E" then return(%_ce_rem(second(args(ex)))),
  ex2:args(ex),
  ex2:map(%_ce_rem, ex2),
  substpart(op(ex), ex2, 0)
)$
compile(%_ce_rem)$
:lisp (setf *standard-input* (make-synonym-stream (quote sb-sys:*stdin*)))
:lisp (setf *standard-output* (make-synonym-stream (quote sb-sys:*stdout*)))
:lisp (setf *error-output* (make-synonym-stream (quote sb-sys:*stderr*)))
:lisp (setf *maxima-started* nil)
:lisp (sb-ext:save-lisp-and-die "{core_path}" :toplevel (quote cl-user::run))
"""
    _run(["maxima", "--very-quiet", f"--batch-string={build_script}"])

    if not core_path.exists():
        raise RuntimeError("Failed to build stackmaxima.core")

    sbcl_path = shutil.which("sbcl") or "/opt/homebrew/bin/sbcl"
    wrapper_content = f"""#!/bin/sh
export PATH="/opt/homebrew/bin:$PATH"
exec "{sbcl_path}" --core "{core_path}" --noinform --end-runtime-options "$@"
"""
    wrapper_path.write_text(wrapper_content, encoding="utf-8")
    wrapper_path.chmod(0o755)

    return wrapper_path


def install_skill_symlink() -> bool:
    """Symlink stack-authoring skill into ~/.gemini/config/skills/ if source exists."""
    workspace_root = Path(__file__).resolve().parent.parent.parent
    source = workspace_root / ".agents" / "skills" / "stack-authoring"
    target_dir = Path.home() / ".gemini" / "config" / "skills"
    target_dir.mkdir(parents=True, exist_ok=True)
    dest = target_dir / "stack-authoring"

    if source.exists() and source.is_dir():
        if dest.is_symlink() or dest.exists():
            if dest.resolve() == source.resolve():
                return True
            if dest.is_symlink():
                dest.unlink()
            elif dest.is_dir():
                shutil.rmtree(dest)
            else:
                dest.unlink()
        dest.symlink_to(source, target_is_directory=True)
        return True
    return False


def _patch_test_controller(qtype_dir: Path) -> None:
    """Ensure TestController properly reinitializes question on each seed in multi-seed test suites."""
    tc_php = qtype_dir / "api" / "controller" / "TestController.php"
    if not tc_php.exists():
        return
    content = tc_php.read_text(encoding="utf-8")
    old_target = """        } else {
            foreach ($question->deployedseeds as $seed) {
                try {
                    $testresponse->results[$seed] = $this->qtype_stack_test_question($question, $testcases, $seed);"""
    replacement = """        } else {
            foreach ($question->deployedseeds as $seed) {
                try {
                    list('question' => $seedQuestion, 'testcases' => $seedCases) = StackQuestionLoader::loadxml($data["questionDefinition"], true);
                    $seedQuestion->castextprocessor = new \\castext2_qa_processor(new \\stack_outofcontext_process());
                    $seedQuestion->seed = (int)$seed;
                    $seedQuestion->initialise_question_from_seed();
                    $testresponse->results[$seed] = $this->qtype_stack_test_question($seedQuestion, $seedCases, $seed);"""
    if old_target in content:
        content = content.replace(old_target, replacement)
        tc_php.write_text(content, encoding="utf-8")


def setup_runtime(force: bool = False, install_skill: bool = True) -> dict[str, Any]:
    """Sets up the complete native STACK runtime:

    - Verifies Homebrew dependencies (PHP, Maxima, SBCL, Gnuplot)
    - Clones moodle-qtype_stack v4.11.0 into ~/.local/share/macstack/qtype_stack
    - Installs composer dependencies in api/
    - Generates maximalocal.mac and api/config.php
    - Compiles the optimised SBCL Maxima image and creates maxima-optimised wrapper
    - Installs stack-authoring skill symlink
    """
    php_version = ensure_homebrew_php()
    maxima_ver_str, maxima_ver_num = get_maxima_version()

    stack_dir = RUNTIME_DIR / "stack"
    for sub in ("logs", "tmp", "plots"):
        (stack_dir / sub).mkdir(parents=True, exist_ok=True)

    qtype_dir = RUNTIME_DIR / "qtype_stack"
    if not qtype_dir.exists() or force:
        if qtype_dir.exists():
            shutil.rmtree(qtype_dir)
        _run([
            "git", "clone",
            "--branch", DEFAULT_STACK_BRANCH,
            "--depth", "1",
            DEFAULT_STACK_REPO,
            str(qtype_dir),
        ])

    api_dir = qtype_dir / "api"
    if not (api_dir / "vendor").exists() or force:
        _run(["composer", "install"], cwd=api_dir)

    _patch_test_controller(qtype_dir)

    maximalocal_mac = generate_maximalocal_mac(RUNTIME_DIR, maxima_ver_str, maxima_ver_num)
    (stack_dir / "maximalocal.mac").write_text(maximalocal_mac, encoding="utf-8")

    php_config = generate_php_config(RUNTIME_DIR, maxima_ver_str)
    (api_dir / "config.php").write_text(php_config, encoding="utf-8")

    wrapper_path = build_precompiled_image(RUNTIME_DIR, force=force)

    skill_installed = False
    if install_skill:
        skill_installed = install_skill_symlink()

    return {
        "ok": True,
        "runtime_dir": str(RUNTIME_DIR),
        "php_version": php_version,
        "maxima_version": maxima_ver_str,
        "stack_version": STACK_VERSION,
        "optimised_image": str(stack_dir / "stackmaxima.core"),
        "wrapper_path": str(wrapper_path),
        "skill_installed": skill_installed,
    }


def find_free_port() -> int:
    """Find a free TCP port on localhost."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def is_process_running(pid: int) -> bool:
    """Check if process with PID is currently alive."""
    try:
        os.kill(pid, 0)
        return True
    except (OSError, ProcessLookupError):
        return False


def stop_php_server() -> bool:
    """Stop the background PHP server if running. Returns True if stopped."""
    server_file = RUNTIME_DIR / "server.json"
    if not server_file.exists():
        return False
    try:
        data = json.loads(server_file.read_text(encoding="utf-8"))
        pid = data.get("pid")
        if pid and is_process_running(pid):
            os.kill(pid, 15)  # SIGTERM
            time.sleep(0.3)
            if is_process_running(pid):
                os.kill(pid, 9)  # SIGKILL
    except Exception:
        pass
    finally:
        if server_file.exists():
            server_file.unlink(missing_ok=True)
    return True


def ensure_php_server() -> str:
    """Ensure the background PHP server is active and healthy.

    Returns the base URL (e.g. 'http://127.0.0.1:8080').
    """
    server_file = RUNTIME_DIR / "server.json"
    if server_file.exists():
        try:
            data = json.loads(server_file.read_text(encoding="utf-8"))
            pid = data.get("pid")
            url = data.get("url")
            if pid and is_process_running(pid) and url:
                try:
                    resp = httpx.get(f"{url}/macstack/health", timeout=1.5)
                    if resp.status_code == 200 and resp.json().get("ok"):
                        return url
                except Exception:
                    pass
        except Exception:
            pass
        stop_php_server()

    # Make sure runtime is initialized
    setup_runtime(force=False, install_skill=False)

    port = find_free_port()
    doc_root = RUNTIME_DIR / "qtype_stack" / "api" / "public"
    router_php = Path(__file__).parent / "php" / "router.php"

    env = os.environ.copy()
    env["MACSTACK_RUNTIME_DIR"] = str(RUNTIME_DIR)
    if "/opt/homebrew/bin" not in env.get("PATH", ""):
        env["PATH"] = f"/opt/homebrew/bin:{env.get('PATH', '')}"

    proc = subprocess.Popen(
        ["php", "-d", "max_execution_time=300", "-d", "memory_limit=512M", "-S", f"127.0.0.1:{port}", "-t", str(doc_root), str(router_php)],
        cwd=str(doc_root),
        env=env,
        start_new_session=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    url = f"http://127.0.0.1:{port}"
    deadline = time.time() + 15.0
    while time.time() < deadline:
        if not is_process_running(proc.pid):
            raise RuntimeError(f"PHP server process {proc.pid} died prematurely")
        try:
            resp = httpx.get(f"{url}/macstack/health", timeout=1.0)
            if resp.status_code == 200 and resp.json().get("ok"):
                server_info = {"pid": proc.pid, "port": port, "url": url}
                server_file.write_text(json.dumps(server_info, indent=2), encoding="utf-8")
                return url
        except Exception:
            pass
        time.sleep(0.2)

    stop_php_server()
    raise TimeoutError("PHP server failed to become healthy within 15 seconds")


