def _run(cmd: list[str], cwd: Path | None = None, check: bool = True) -> subprocess.CompletedProcess[str]:
    """Helper to run a shell command."""
    env = os.environ.copy()
    if "/opt/homebrew/bin" not in env.get("PATH", ""):
        env["PATH"] = f"/opt/homebrew/bin:{env.get('PATH', '')}"
    return subprocess.run(
        cmd,
        cwd=cwd,
        check=check,
        capture_output=True,
        text=True,
        env=env,
    )


def get_maxima_version() -> tuple[str, float]:
    """Retrieve installed Maxima version string (e.g.

    '5.50.0') and float (e.g. 50.0).
    """
    try:
        proc = _run(["maxima", "--version"])
        out = proc.stdout.strip()
        m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", out)
        if m:
            full_ver = m.group(0)
            minor = float(m.group(2))
            return full_ver, minor
    except Exception:
        pass
    return "5.50.0", 50.0


def ensure_homebrew_php() -> str:
    """Ensure PHP is installed via Homebrew and return version string."""
    php_path = shutil.which("php") or "/opt/homebrew/bin/php"
    if not os.path.exists(php_path):
        _run(["brew", "install", "php"])
    proc = _run(["php", "--version"])
    return proc.stdout.splitlines()[0] if proc.stdout else "PHP installed"


