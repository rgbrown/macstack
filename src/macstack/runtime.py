def doctor() -> dict[str, Any]:
    """Run diagnostics on environment, Maxima, PHP bridge, CAS latency, and SVG plotting."""
    checks: list[dict[str, Any]] = []

    # 1. Binary checks
    for bin_name in ("php", "maxima", "sbcl", "gnuplot"):
        path = shutil.which(bin_name) or f"/opt/homebrew/bin/{bin_name}"
        found = os.path.exists(path)
        checks.append({
            "name": f"binary_{bin_name}",
            "passed": found,
            "details": f"Found at {path}" if found else "Not found in PATH or /opt/homebrew/bin",
        })

    # 2. Files checks
    core_path = RUNTIME_DIR / "stack" / "stackmaxima.core"
    opt_wrapper = RUNTIME_DIR / "stack" / "maxima-optimised"
    checks.append({
        "name": "stackmaxima_core",
        "passed": core_path.exists(),
        "details": f"File size: {core_path.stat().st_size} bytes" if core_path.exists() else "Missing core",
    })
    checks.append({
        "name": "maxima_optimised_wrapper",
        "passed": opt_wrapper.exists() and os.access(opt_wrapper, os.X_OK),
        "details": str(opt_wrapper) if opt_wrapper.exists() else "Missing executable wrapper",
    })

    # 3. Server health check
    server_url = ""
    try:
        server_url = ensure_php_server()
        checks.append({
            "name": "php_bridge_server",
            "passed": True,
            "details": f"Active at {server_url}",
        })
    except Exception as e:
        checks.append({
            "name": "php_bridge_server",
            "passed": False,
            "details": f"Failed to start/reach PHP server: {e}",
        })

    # 4. CAS latency & SVG Plot render check
    cas_latency_ms = 0.0
    if server_url:
        try:
            t0 = time.perf_counter()
            resp = httpx.post(
                f"{server_url}/render",
                json={"questionDefinition": SAMPLE_DIAGNOSTIC_XML, "seed": 1, "renderInputs": "ans_"},
                timeout=15.0,
            )
            cas_latency_ms = round((time.perf_counter() - t0) * 1000, 2)
            if resp.status_code == 200:
                data = resp.json()
                render_html = data.get("questionrender", "")
                assets = data.get("questionassets", {})

                svg_found = False
                plot_file = ""
                # Check assets map for any svg file
                for _k, v in (assets.items() if isinstance(assets, dict) else []):
                    if str(v).endswith(".svg"):
                        svg_found = True
                        plot_file = str(v)
                        break
                if not svg_found and ".svg" in render_html:
                    svg_found = True

                plot_valid = False
                if plot_file:
                    plot_resp = httpx.get(f"{server_url}/plots/{plot_file}", timeout=5.0)
                    if plot_resp.status_code == 200 and plot_resp.content.startswith(b"<?xml") or b"<svg" in plot_resp.content:
                        plot_valid = True

                checks.append({
                    "name": "cas_render_and_svg_plot",
                    "passed": svg_found and (plot_valid or not plot_file),
                    "details": f"Rendered in {cas_latency_ms}ms, plot asset: {plot_file}",
                })
            else:
                checks.append({
                    "name": "cas_render_and_svg_plot",
                    "passed": False,
                    "details": f"HTTP {resp.status_code}: {resp.text}",
                })
        except Exception as e:
            checks.append({
                "name": "cas_render_and_svg_plot",
                "passed": False,
                "details": f"Render exception: {e}",
            })

    ok = all(c["passed"] for c in checks)
    return {
        "ok": ok,
        "checks": checks,
        "cas_latency_ms": cas_latency_ms,
        "stack_version": STACK_VERSION,
    }
